def get_vaccines_for_child(birth_date, today):
    """
    Возвращает список прививок с рассчитанной датой для конкретного ребёнка.
    birth_date, today — объекты datetime.date
    """
    results = []
    for v in VACCINE_SCHEDULE:
        from datetime import timedelta
        due_date = birth_date + timedelta(days=v["days"])
        results.append({
            "name": v["name"],
            "info": v["info"],
            "due_date": due_date,
            "days_left": (due_date - today).days,
        })
    return results
